const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const ctx={window:{},Blob,console};
for(const file of ['analyzer.js','resonare-v08.js','loop-arranger-v09.js','motif-planner-v01.js','melodic-grammar-v01.js','tension-r2a.js','tension-r2b.js','m2-emotion-phrase-v01.js','m3-harmony-melody-v01.js','m5-performance-v01.js','handheld-v21.js'])
 vm.runInNewContext(fs.readFileSync(file,'utf8'),ctx,{filename:file});
const A=ctx.window.PlotuneAnalysis,H=ctx.window.PlotuneHandheld,T=ctx.window.PlotuneTensionR2a;
const input={title:'R2 dynamics',character:'旅人',world:'森',scene:'帰る',style:'handheld',duration:15};
const plan=A.plan(input,A.analyze(input));
const opts={...H.prepare(plan,'journey',null,false,input.scene),musicDevelopment:true,musicHarmony:true,musicPerformance:true};
const tensionPlan=T.plan({emotionPlan:{sections:[{name:'one'},{name:'two'}]}},{dynamic:[0,1]});
const off=H.score(opts),on=H.score({...opts,musicTensionR2:true,tensionPlan});
assert.equal(JSON.stringify(on.harmony),JSON.stringify(off.harmony),'chords unchanged');
assert.notEqual(JSON.stringify(on.notes),JSON.stringify(off.notes),'M5 dynamics changes rendered score');
assert(on.details.tensionR2.dynamicsApplied>0);
assert.equal(on.details.tensionR2.mode,'dynamics-applied');
assert.equal(JSON.stringify(on.notes),JSON.stringify(H.score({...opts,musicTensionR2:true,tensionPlan}).notes),'deterministic ON');
assert.equal(JSON.stringify(off.notes),JSON.stringify(H.score(opts).notes),'OFF preserved');
const shadow=H.score({...opts,musicPerformance:false,musicTensionR2:true,tensionPlan});
const shadowOff=H.score({...opts,musicPerformance:false});
assert.equal(JSON.stringify(shadow.notes),JSON.stringify(shadowOff.notes),'M5 absent means no sound change');
const pcmOff=H.render(opts).samples,pcmOn=H.render({...opts,musicTensionR2:true,tensionPlan}).samples;
assert.equal(pcmOn.length,pcmOff.length);
let difference=0;for(let i=0;i<pcmOn.length;i+=211)difference+=Math.abs(pcmOn[i]-pcmOff[i]);
assert(difference>0,'R2 explicit dynamics produces PCM difference');
assert.throws(()=>ctx.window.PlotuneM5Performance.express({notes:[],duration:2,meter:1,tensionDynamics:[1.4]}),/invalid tensionDynamics/);

const inverted=T.plan({emotionPlan:{sections:[{name:'one'},{name:'two'}]}},{dynamic:[1,0]});
const opposite=H.score({...opts,musicTensionR2:true,tensionPlan:inverted});
const melodyIdentity=score=>JSON.stringify(score.notes.map(({volume,...rest})=>rest));
assert.equal(melodyIdentity(on),melodyIdentity(opposite),'same emotion, alternative tension has same musical events');
assert.equal(JSON.stringify(on.harmony),JSON.stringify(opposite.harmony),'same emotion, alternative tension leaves harmony unchanged');
assert.notEqual(JSON.stringify(on.notes),JSON.stringify(opposite.notes),'same emotion, alternative tension changes volume trajectory');
const one=H.render({...opts,musicTensionR2:true,tensionPlan:inverted}).samples;
let oppositePCM=0;for(let i=0;i<one.length;i+=211)oppositePCM+=Math.abs(one[i]-pcmOn[i]);
assert(oppositePCM>0,'same emotional trajectory and inverted tension target yield different PCM');
const noDynamic=T.plan({emotionPlan:{sections:[{name:'one'},{name:'two'}]}},{tonal:[0,1]});
const tonalOnly=H.score({...opts,musicTensionR2:true,tensionPlan:noDynamic});
assert.equal(JSON.stringify(tonalOnly.notes),JSON.stringify(off.notes),'unknown dynamic target must not affect audio');
assert.equal(tonalOnly.details.tensionR2.mode,'shadow-only');
console.log('PASS R2b M5 dynamic target: ON/OFF score and PCM difference, no candidate selection, deterministic');
