const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const root=path.resolve(__dirname,'..'),window={},context={window,Blob,console};
for(const filename of ['analyzer.js','resonare-v08.js','composer-v04.js'])vm.runInNewContext(fs.readFileSync(path.join(root,filename),'utf8'),context,{filename});
const A=window.PlotuneAnalysis,R=window.PlotuneResonare,C=window.PlotuneComposerV4;
const input={title:'複合感情',character:'',world:'',scene:'昔を思い出して泣いた。突然物音に怯え、最後には安心した。',style:'piano',duration:15};
const original=A.plan(input,A.analyze(input));
const without=C.buildScore(original);
const withEmotion=C.buildScore({...original,emotionComposition:true});
assert.equal(without.details.emotionComposition,false);
assert.equal(withEmotion.details.emotionComposition,true);
assert.deepEqual(Array.from(without.theme),Array.from(withEmotion.theme));
assert.equal(without.bpm,withEmotion.bpm);
assert.equal(without.genre,withEmotion.genre);
assert.ok(withEmotion.details.emotionSections.length===4);
const standardResonare=R.attachPlan(original,R.analyze(input));
assert.equal(!!standardResonare.resonare,true);
const app=fs.readFileSync(path.join(root,'app-v13.js'),'utf8');
assert.ok(app.includes('enhanced={...original,emotionComposition:true}'),'Phase 1 must not use Resonare enhanced plan');
assert.ok(app.includes('▶ 感情表現OFF')&&app.includes('▶ 感情表現ON'),'A/B labels must identify the controlled comparison');
assert.notDeepEqual(without.notes,withEmotion.notes,'ON should affect the score for the fixture');
console.log('PASS isolated Phase 1 A/B: same plan / seed / genre / BPM, differing emotional rendering without Resonare');
