const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const context={window:{}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'..','m6-quality-v01.js'),'utf8'),context);
const M=context.window.PlotuneM6Quality;
const bar=(t)=>[0,1,2,3].map((x)=>({t:t+x,d:.5,midi:60+x,voice:'lead',volume:.2}));
const notes=[...bar(0),...bar(4)];
const input=JSON.stringify(notes);
const a=M.assess({notes,meter:4,duration:8});
assert.equal(a.metrics.repetition,1);
const result=M.repair({notes,meter:4,duration:8,issue:a.issues[0],seed:1});
assert.equal(result.accepted,true);
assert.equal(result.after.metrics.repetition,0);
assert.equal(JSON.stringify(notes),input,'source remains unchanged');
assert.equal(JSON.stringify(result.notes.slice(0,4)),JSON.stringify(notes.slice(0,4)),'other bar preserved');
assert.equal(JSON.stringify(result),JSON.stringify(M.repair({notes,meter:4,duration:8,issue:a.issues[0],seed:1})),'deterministic');
assert.equal(M.repair({notes,meter:4,duration:8,issue:{bar:0,metric:'unresolvedEnding'}}).accepted,false);
assert.throws(()=>M.assess({notes,duration:0,meter:4}),/valid timing/);
console.log('PASS M6 local assessment and bounded repair');
