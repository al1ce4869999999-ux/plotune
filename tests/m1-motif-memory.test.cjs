const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path'),assert=require('node:assert/strict');
const ctx={window:{}},root=path.resolve(__dirname,'..');
vm.runInNewContext(fs.readFileSync(path.join(root,'m-motif-memory-v01.js'),'utf8'),ctx);
const m=ctx.window.PlotuneMotifMemory;
const events=[{degree:2,position:0,durationUnits:2},{degree:4,position:2,durationUnits:1,accent:true},{degree:3,position:3,durationUnits:1,rest:true}];
const source=JSON.stringify(events),original=m.register('theme-a',events,{chord:'I'});
assert.equal(original.motifId,'theme-a');
assert.deepEqual(Array.from(original.pitchIntervals),[2,-1]);
assert.deepEqual(Array.from(original.accents),[false,true,false]);
const reprise=m.recall(original,'A-return');
assert.deepEqual(Array.from(reprise.events,x=>x.degree),[2,4,3]);
assert.equal(reprise.variationHistory.at(-1).operation,'recall');
const raised=m.transpose(original,2,'B');
assert.deepEqual(Array.from(raised.events,x=>x.degree),[4,6,5]);
assert.equal(raised.variationHistory.at(-1).operation,'transpose');
assert.equal(raised.variationHistory.at(-1).amount,2);
assert.equal(JSON.stringify(events),source,'source untouched');
assert.deepEqual(Array.from(original.events,x=>x.degree),[2,4,3]);
assert.throws(()=>m.register('',events),/motifId/);
assert.throws(()=>m.register('x',[{degree:1,position:0,durationUnits:-1}]),/invalid/);
assert.throws(()=>m.transpose(original,1.4,'B'),/integer/);
console.log('PASS M1-1 motif registration, recall and transpose');
