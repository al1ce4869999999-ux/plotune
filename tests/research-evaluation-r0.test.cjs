const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const source=fs.readFileSync(path.join(__dirname,'..','research-evaluation-r0.js'),'utf8');
const ctx={window:{}};vm.runInNewContext(source,ctx,{filename:'research-evaluation-r0.js'});
const r=ctx.window.PlotuneResearchEvaluation;
const score={notes:[{t:0,midi:60,volume:0.8}]},plan={seed:123,sections:[{role:'intro'}]},context={mode:'baseline'};
const original=JSON.stringify([score,plan,context]);
const ok=r.evaluate((s,p,c)=>{s.notes[0].midi=63;p.sections[0].role='x';c.mode='changed';return {metrics:{noteCount:s.notes.length},diagnostics:[]};},score,plan,context);
assert.equal(ok.status,'ok');assert.equal(ok.metrics.noteCount,1);
assert.equal(JSON.stringify([score,plan,context]),original);
assert.equal(r.evaluate(()=>({metrics:{bad:Infinity}}),score,plan,context).status,'fallback');
assert.equal(r.evaluate(()=>{throw Error('failed');},score,plan,context).status,'fallback');
const trace={version:'0.1',entries:[{id:'GEN01'}]};
const recorded=r.record(trace,ok,'diagnostic only');
assert.equal(trace.researchEvaluations,undefined);
assert.equal(recorded.entries.length,1);assert.equal(recorded.researchEvaluations[0].selectionReason,'diagnostic only');
assert.equal(r.compare(score,JSON.parse(JSON.stringify(score))).equal,true);
assert.equal(r.compare(score,{notes:[]}).changed,true);
console.log('PASS R0 read-only evaluator, fallback, trace and baseline comparison');
