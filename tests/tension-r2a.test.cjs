const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const math=Object.create(Math);math.random=()=>{throw Error('R2a RNG consumption');};
const ctx={window:{},Math:math};
for(const f of ['research-evaluation-r0.js','tension-r2a.js'])vm.runInNewContext(fs.readFileSync(f,'utf8'),ctx,{filename:f});
const R=ctx.window.PlotuneResearchEvaluation,T=ctx.window.PlotuneTensionR2a;
const source={tensionTarget:.7,emotionPlan:{sections:[{name:'A',start:0,end:4,target:{sadness:.8}},{name:'B',start:4,end:8,target:{sadness:.8}}]}};
const before=JSON.stringify(source);
const p=T.plan(source,{tonal:[.1,.9],rhythmic:[.9,.1]});
assert.equal(p.sections.length,2);
assert.equal(p.legacyTensionTarget,.7);
assert.equal(p.sections[0].target.timbral,null);
assert.equal(p.sections[0].target.tonal,.1);
assert.equal(p.sections[1].target.tonal,.9);
assert.equal(p.sections[0].target.rhythmic,.9);
assert.equal(JSON.stringify(source),before);
assert.throws(()=>T.plan(source,{tonal:[2,0]}),/invalid tension/);
const notes=[{t:0,d:1,midi:60,velocity:.3,instrument:'piano'},{t:1,d:1,midi:64,velocity:.5,instrument:'piano'},{t:3,d:1,midi:67,velocity:.9,instrument:'piano'}];
const old=JSON.stringify(notes);
const result=R.evaluate((score,plan)=>T.evaluate(score,plan),{notes},p,{});
assert.equal(result.status,'ok');
for(const k of ['tonal','expectancy','rhythmic','density','timbral','dynamic'])assert(Number.isFinite(result.metrics[k]),k);
const trace=R.record({},result,'R2a diagnosis only');
assert.equal(trace.researchEvaluations.length,1);
assert.equal(JSON.stringify(notes),old);
const unknown=R.evaluate((score)=>T.evaluate(score),{notes:notes.map(({t,d,midi})=>({t,d,midi}))},{},{});
assert.equal(unknown.status,'ok');
assert.equal(unknown.metrics.dynamic,undefined);
assert.equal(unknown.metrics.timbral,undefined);
assert(unknown.diagnostics.some(x=>x.code==='TIMBRAL_UNKNOWN'));
assert.equal(R.evaluate(()=>T.evaluate({notes:[{t:-1,d:1,midi:60}]}),{}, {},{}).status,'fallback');
console.log('PASS R2a independent six-component plan, trace, RNG, fallbacks, missing-data handling');
